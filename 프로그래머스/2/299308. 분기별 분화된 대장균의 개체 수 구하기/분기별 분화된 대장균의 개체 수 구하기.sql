-- 각 분기별 분화된 대장균의 개체의 총 수 출력 sql
-- 각 분기에는 q 붙이고, 분기에 대해 오른차순 정렬

SELECT T.QUARTER, COUNT(*) as ECOLI_COUNT
FROM (SELECT CASE 
WHEN MONTH(DIFFERENTIATION_DATE) IN (1,2,3) THEN '1Q'
WHEN MONTH(DIFFERENTIATION_DATE) IN (4,5,6) THEN '2Q'
WHEN MONTH(DIFFERENTIATION_DATE) IN (7,8,9)THEN '3Q'
ELSE '4Q'
END as QUARTER
FROM ECOLI_DATA) as T
GROUP BY T.QUARTER
ORDER BY T.QUARTER