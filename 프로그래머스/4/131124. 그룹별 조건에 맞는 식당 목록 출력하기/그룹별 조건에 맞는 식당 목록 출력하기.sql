-- 리뷰에서 가장 많이 작성한 회원의 리뷰 조회
-- MEMBER_NAME, REVIEW_TEXT, REVIEW_DATE
-- REVIEW_DATE ASC , REVIEW_TEXT ASC

WITH MEMBER_CNT as  (
    SELECT m.MEMBER_ID, COUNT(r.REST_ID) as R_CNT
    FROM MEMBER_PROFILE as m JOIN REST_REVIEW as r
    ON m.MEMBER_ID = r.MEMBER_ID
    GROUP BY MEMBER_ID
    ORDER BY R_CNT DESC limit 1 
)

SELECT m2.MEMBER_NAME, r.REVIEW_TEXT, r.REVIEW_DATE
FROM MEMBER_CNT as m JOIN REST_REVIEW as r
ON m.MEMBER_ID = r.MEMBER_ID JOIN
MEMBER_PROFILE as m2 
ON m.MEMBER_ID = m2.MEMBER_ID
ORDER BY r.REVIEW_DATE ASC, r.REVIEW_TEXT ASC 