-- 자동차 종류가 '트럭'인 자동차의 대여 기록에 대해
-- 대여 기록 별 대여 금액을 구하고
-- 대여기록 id와 대여금액 리스트를 출력
-- 대여금액 기준 desc, 기록 id 기준 desc 
WITH TRUCK_DISCOUNT as (
    SELECT CC.CAR_ID as CAR_ID, CC.CAR_TYPE as CAR_TYPE, CC.DAILY_FEE as DAILY_FEE, CP.DURATION_TYPE as DURATION_TYPE, CP.DISCOUNT_RATE as DISCOUNT_RATE
    FROM CAR_RENTAL_COMPANY_CAR as CC
    JOIN CAR_RENTAL_COMPANY_DISCOUNT_PLAN as CP
    ON CC.CAR_TYPE = CP.CAR_TYPE
    WHERE CC.CAR_TYPE = '트럭'
)

SELECT DISTINCT(CH.HISTORY_ID), 
CASE WHEN
     DATEDIFF(CH.END_DATE, CH.START_DATE) + 1 >= 7 AND   DATEDIFF(CH.END_DATE, CH.START_DATE) + 1 < 30 THEN FLOOR(TRUCK_DISCOUNT.DAILY_FEE * ( DATEDIFF(CH.END_DATE, CH.START_DATE) + 1 ) * (1-0.05))
     WHEN
     DATEDIFF(CH.END_DATE, CH.START_DATE) + 1 >= 30 AND   DATEDIFF(CH.END_DATE, CH.START_DATE) + 1 < 90 THEN  FLOOR(TRUCK_DISCOUNT.DAILY_FEE * ( DATEDIFF(CH.END_DATE, CH.START_DATE) + 1 ) * (1-0.07))
          WHEN
     DATEDIFF(CH.END_DATE, CH.START_DATE) + 1 >= 90 THEN  FLOOR(TRUCK_DISCOUNT.DAILY_FEE * ( DATEDIFF(CH.END_DATE, CH.START_DATE) + 1 ) * (1-0.1))
     ELSE FLOOR(TRUCK_DISCOUNT.DAILY_FEE * ( DATEDIFF(CH.END_DATE, CH.START_DATE) + 1 ))
END as FEE
FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY as CH JOIN
TRUCK_DISCOUNT
ON CH.CAR_ID = TRUCK_DISCOUNT.CAR_ID
WHERE TRUCK_DISCOUNT.CAR_TYPE = '트럭' 
ORDER BY FEE DESC, CH.HISTORY_ID DESC